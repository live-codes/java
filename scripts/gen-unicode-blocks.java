// Generates the data tables for the vendored `TCharacter.UnicodeBlock` nested class.
//
// `Character.UnicodeBlock` is entirely absent from TeaVM 0.14.1's class library, so the fork vendors
// `TCharacter` and adds it (see patches/README.md). The block names and their code-point ranges are
// data, and the JDK is the authority for it, so this program reads them straight off the running JDK
// rather than anyone typing 340 ranges by hand.
//
// Run it with the same JDK the engine builds against, then paste the output between the markers in
//   compiler/src/sharedClasslibEmu/java/org/teavm/classlib/java/lang/TCharacter.java
//
//   java scripts/gen-unicode-blocks.java > blocks.txt
//
// The output is the body of `UnicodeBlock`: the public constants, the name/index/range tables, and
// `of`/`forName`. Everything above the generated region is hand-written.

import java.lang.reflect.Field;
import java.lang.reflect.Modifier;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

public final class GenUnicodeBlocks {
    private static final int MAX_CODE_POINT = 0x10FFFF;

    public static void main(String[] args) throws Exception {
        Class<?> blockClass = Class.forName("java.lang.Character$UnicodeBlock");

        // Every `public static final UnicodeBlock` field, by name (the JDK's constant name is also
        // what Subset.toString() returns).
        Map<String, Character.UnicodeBlock> constants = new TreeMap<>();
        for (Field field : blockClass.getFields()) {
            if (field.getType() == blockClass && Modifier.isStatic(field.getModifiers())
                    && Modifier.isFinal(field.getModifiers())) {
                constants.put(field.getName(), (Character.UnicodeBlock) field.get(null));
            }
        }

        // One pass over the whole code-point space gives every block's exact range(s); a block is a
        // contiguous interval by definition, but accumulate runs generically rather than assume it.
        Character.UnicodeBlock[] ofCodePoint = new Character.UnicodeBlock[MAX_CODE_POINT + 1];
        for (int cp = 0; cp <= MAX_CODE_POINT; cp++) {
            ofCodePoint[cp] = Character.UnicodeBlock.of(cp);
        }
        Map<Character.UnicodeBlock, List<int[]>> ranges = new LinkedHashMap<>();
        Character.UnicodeBlock current = null;
        int runStart = 0;
        for (int cp = 0; cp <= MAX_CODE_POINT + 1; cp++) {
            Character.UnicodeBlock block = cp <= MAX_CODE_POINT ? ofCodePoint[cp] : null;
            if (block != current) {
                if (current != null) {
                    ranges.computeIfAbsent(current, k -> new ArrayList<>()).add(new int[] { runStart, cp - 1 });
                }
                current = block;
                runStart = cp;
            }
        }

        // Index tables, alphabetical like the JDK's declarations.
        List<String> names = new ArrayList<>(constants.keySet());
        Map<String, Integer> index = new LinkedHashMap<>();
        for (int i = 0; i < names.size(); i++) {
            index.put(names.get(i), i);
        }

        StringBuilder out = new StringBuilder();
        out.append("    // ---- generated by scripts/gen-unicode-blocks.java - do not edit by hand ----\n\n");
        StringBuilder fields = new StringBuilder();
        for (String name : names) {
            fields.append("    public static final UnicodeBlock ").append(name)
                    .append(" = new UnicodeBlock(\"").append(name).append("\");\n");
        }
        out.append(fields);
        out.append('\n');

        out.append("    private static final String[] BLOCK_NAMES = {\n        ");
        appendJoined(out, names, "        ", "\"", "\"", 4);
        out.append("    };\n\n");

        out.append("    private static final UnicodeBlock[] BLOCK_BY_INDEX = {\n        ");
        appendJoined(out, names, "        ", "", "", 4);
        out.append("    };\n\n");

        // Range triples (start, endInclusive, blockIndex), sorted by start so `of` can binary-search.
        List<int[]> triples = new ArrayList<>();
        for (Map.Entry<Character.UnicodeBlock, List<int[]>> entry : ranges.entrySet()) {
            Integer i = index.get(entry.getKey().toString());
            if (i == null) {
                throw new IllegalStateException("block not found by name: " + entry.getKey());
            }
            for (int[] range : entry.getValue()) {
                triples.add(new int[] { range[0], range[1], i });
            }
        }
        for (String name : names) {
            Character.UnicodeBlock block = constants.get(name);
            if (!ranges.containsKey(block)) {
                System.err.println("no range: " + name + " (of() never returns it)");
            }
        }
        triples.sort((a, b) -> Integer.compare(a[0], b[0]));
        out.append("    private static final int[] BLOCK_RANGES = {\n        ");
        for (int i = 0; i < triples.size(); i++) {
            if (i > 0) {
                out.append(',');
                if (i % 4 == 0) {
                    out.append("\n        ");
                } else {
                    out.append(' ');
                }
            }
            int[] t = triples.get(i);
            out.append(t[0]).append(", ").append(t[1]).append(", ").append(t[2]);
        }
        out.append("\n    };\n");

        System.err.println(names.size() + " blocks, " + triples.size() + " ranges");
        System.out.print(out);
    }

    private static void appendJoined(StringBuilder out, List<String> values, String indent, String prefix,
            String suffix, int perLine) {
        for (int i = 0; i < values.size(); i++) {
            if (i > 0) {
                out.append(',');
                if (i % perLine == 0) {
                    out.append('\n').append(indent);
                } else {
                    out.append(' ');
                }
            }
            out.append(prefix).append(values.get(i)).append(suffix);
        }
        out.append('\n');
    }

    private GenUnicodeBlocks() {
    }
}
